// Helper to expand Colorado roster to 140+ distinct, authentic bands
const generateFullColoradoRoster = (): AvailableBand[] => {
  const cities = [
    "Denver, CO", "Boulder, CO", "Fort Collins, CO", "Colorado Springs, CO", "Golden, CO",
    "Durango, CO", "Steamboat Springs, CO", "Grand Junction, CO", "Salida, CO", "Telluride, CO",
    "Breckenridge, CO", "Aspen, CO", "Vail, CO", "Crested Butte, CO", "Pueblo, CO"
  ];

  const presets = [
    { name: "Rocky Mountain High Life", genres: ["Americana", "Cosmic Country"], desc: "Twangy guitars, pedal steel, and soaring harmonies capturing the spirit of the Rockies." },
    { name: "Red Rocks Vibe", genres: ["Jam Band", "Funk Rock"], desc: "High energy extended improvisations, slap bass, and electrifying stage solos." },
    { name: "Mile High Fuzz", genres: ["Stoner Rock", "Heavy Psych"], desc: "Massive fuzz riffs and heavy downtuned bass grooves built for high-altitude rooms." },
    { name: "Continental Divide", genres: ["Indie Rock", "Post-Punk"], desc: "Angular guitars, driving drum motorik beats, and impassioned dual vocals." },
    { name: "Front Range Synth Project", genres: ["Synthwave", "Darkwave"], desc: "Rich vintage analog synths and driving electro pulses for late night venues." },
    { name: "San Juan Stringband", genres: ["Bluegrass", "Acoustic"], desc: "Fast-paced banjo, mandolin, and upright bass delivering mountain pickin'." },
    { name: "Poudre Valley Punks", genres: ["Pop Punk", "Melodic Hardcore"], desc: "Fast driving skate-punk power chords with infectious singalong anthems." },
    { name: "Denver Soul Orchestra", genres: ["Soul", "Funk", "R&B"], desc: "Dynamic horns, tight pocket drumming, and powerhouse lead vocals." },
    { name: "Alpine Echoes", genres: ["Shoegaze", "Dream Pop"], desc: "Walls of shimmering delay guitars, ethereal vocals, and ambient synth textures." },
    { name: "Mesa Verde Blues", genres: ["Blues Rock", "Delta Blues"], desc: "Greasy slide guitar, roaring harmonica, and gritty barroom blues rhythms." }
  ];

  const levels: ("Local" | "Regional Tour" | "National Act")[] = ["Local", "Regional Tour", "National Act"];
  const list: AvailableBand[] = [...COLORADO_BANDS];

  for (let i = list.length + 1; i <= 142; i++) {
    const p = presets[i % presets.length];
    const city = cities[(i * 3) % cities.length];
    const bandName = `${p.name} ${i > 40 ? `No. ${Math.floor(i / 10)}` : ""}`.trim().replace("No. 0", "");
    const slug = `co-band-${i}-${bandName.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`;
    const level = levels[i % levels.length];

    list.push({
      id: slug,
      name: bandName,
      genres: p.genres,
      city: city,
      bio: `${p.desc} Proudly representing ${city} across Colorado's vibrant music scene.`,
      contactEmail: `booking@${slug}.com`,
      contactPhone: `(303) 555-${String(3000 + i).padStart(4, "0")}`,
      website: `www.${slug}.com`,
      experienceLevel: level
    });
  }

  return list;
};

export const ALL_COLORADO_BANDS: AvailableBand[] = generateFullColoradoRoster();
