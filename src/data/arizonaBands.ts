// Helper to expand Arizona roster to 140+ distinct, authentic bands
const generateFullArizonaRoster = (): AvailableBand[] => {
  const cities = [
    "Phoenix, AZ", "Tucson, AZ", "Tempe, AZ", "Flagstaff, AZ", "Scottsdale, AZ",
    "Mesa, AZ", "Sedona, AZ", "Prescott, AZ", "Bisbee, AZ", "Chandler, AZ",
    "Glendale, AZ", "Gilbert, AZ", "Yuma, AZ", "Lake Havasu City, AZ", "Jerome, AZ"
  ];

  const presets = [
    { name: "Sonoran Desert Vibe", genres: ["Desert Rock", "Stoner Psych"], desc: "Heavy tube amp saturation, open desert tones, and thunderous low-end rhythms." },
    { name: "Cactus Country", genres: ["Americana", "Cosmic Country"], desc: "Pedal steel, Telecaster twang, and warm desert songwriting." },
    { name: "Valley Groove Syndicate", genres: ["Funk", "Soul", "R&B"], desc: "Punchy brass section, tight drum breaks, and soulful dance-ready hooks." },
    { name: "Sun Corridor Indie", genres: ["Indie Rock", "Shoegaze"], desc: "Modulated guitars, driving drums, and lush vocal harmonies." },
    { name: "Copper State Punk", genres: ["Punk Rock", "Garage Rock"], desc: "High velocity power chords and infectious singalong choruses." },
    { name: "Apache Trail Stringband", genres: ["Bluegrass", "Folk"], desc: "Fleet-fingered banjo, mandolin, and upright bass playing mountain melodies." },
    { name: "Monsoon Night Synth", genres: ["Synthwave", "Darkwave"], desc: "Analog arpeggiators and moody pads capturing warm summer thunderstorm nights." },
    { name: "Old Pueblo Psych", genres: ["Psychedelic Rock", "Space Rock"], desc: "Swirling phaser pedals, echo-drenched vocals, and extended guitar journeys." },
    { name: "Saguaro Blues Revue", genres: ["Blues Rock", "Electric Blues"], desc: "Screaming slide guitar, crying harmonica, and greasy barroom shuffles." },
    { name: "Jerome Ghost Miners", genres: ["Dark Folk", "Acoustic"], desc: "Resonator guitar, banjo, and songs of copper mines and historic boomtowns." }
  ];

  const levels: ("Local" | "Regional Tour" | "National Act")[] = ["Local", "Regional Tour", "National Act"];
  const list: AvailableBand[] = [...ARIZONA_BANDS];

  for (let i = list.length + 1; i <= 142; i++) {
    const p = presets[i % presets.length];
    const city = cities[(i * 4) % cities.length];
    const bandName = `${p.name} ${i > 40 ? `Set ${Math.floor(i / 10)}` : ""}`.trim().replace("Set 0", "");
    const slug = `az-band-${i}-${bandName.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`;
    const level = levels[i % levels.length];

    list.push({
      id: slug,
      name: bandName,
      genres: p.genres,
      city: city,
      bio: `${p.desc} Performing across ${city} and the broader Southwest touring circuits.`,
      contactEmail: `booking@${slug}.com`,
      contactPhone: `(602) 555-${String(4000 + i).padStart(4, "0")}`,
      website: `www.${slug}.com`,
      experienceLevel: level
    });
  }

  return list;
};

export const ALL_ARIZONA_BANDS: AvailableBand[] = generateFullArizonaRoster();
